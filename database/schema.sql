-- CareConnect schema (MySQL 8). Run once in MySQL Workbench.
CREATE DATABASE IF NOT EXISTS careconnect CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE careconnect;

CREATE TABLE users (
    id            BIGINT AUTO_INCREMENT PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    email         VARCHAR(150) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          ENUM('PARENT','CHILD') NOT NULL,
    created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_users_email UNIQUE (email)
);

-- One row per parent<->child link. status flow: PENDING -> APPROVED (or REJECTED)
CREATE TABLE family_connections (
    id             BIGINT AUTO_INCREMENT PRIMARY KEY,
    parent_id      BIGINT NOT NULL,
    child_id       BIGINT NOT NULL,
    status         ENUM('PENDING','APPROVED','REJECTED') NOT NULL DEFAULT 'PENDING',
    share_checkins BOOLEAN NOT NULL DEFAULT FALSE,   -- parent consent for check-in visibility
    created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    approved_at    TIMESTAMP NULL,
    CONSTRAINT uq_family_pair UNIQUE (parent_id, child_id),
    CONSTRAINT fk_fc_parent FOREIGN KEY (parent_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_fc_child  FOREIGN KEY (child_id)  REFERENCES users(id) ON DELETE CASCADE,
    INDEX idx_fc_child_status (child_id, status)
);

-- Single-use, expiring code generated by a parent
CREATE TABLE invitation_tokens (
    id         BIGINT AUTO_INCREMENT PRIMARY KEY,
    parent_id  BIGINT NOT NULL,
    code       VARCHAR(12) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    used       BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_invite_code UNIQUE (code),
    CONSTRAINT fk_inv_parent FOREIGN KEY (parent_id) REFERENCES users(id) ON DELETE CASCADE
);

-- Soft delete (active=false) keeps historical logs intact
CREATE TABLE medications (
    id               BIGINT AUTO_INCREMENT PRIMARY KEY,
    parent_id        BIGINT NOT NULL,
    name             VARCHAR(120) NOT NULL,
    type             ENUM('TABLET','CAPSULE','SYRUP') NOT NULL,
    strength         VARCHAR(50),
    dosage_per_dose  DECIMAL(6,2) NOT NULL,           -- units consumed per dose (e.g. 1 tablet, 5 ml)
    quantity_unit    ENUM('TABLET','CAPSULE','ML') NOT NULL,
    frequency_label  VARCHAR(60) NOT NULL,            -- e.g. "Twice daily"
    food_instruction ENUM('BEFORE_FOOD','AFTER_FOOD','WITH_FOOD','ANY_TIME') NOT NULL DEFAULT 'ANY_TIME',
    notes            VARCHAR(500),
    start_date       DATE NOT NULL,
    end_date         DATE NULL,
    active           BOOLEAN NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_med_parent FOREIGN KEY (parent_id) REFERENCES users(id) ON DELETE CASCADE,
    INDEX idx_med_parent_active (parent_id, active)
);

-- Planned dose times (one row per daily dose time). Frequency = number of rows.
CREATE TABLE medication_schedules (
    id            BIGINT AUTO_INCREMENT PRIMARY KEY,
    medication_id BIGINT NOT NULL,
    dose_time     TIME NOT NULL,
    active        BOOLEAN NOT NULL DEFAULT TRUE,   -- soft delete (added Day 4)
    CONSTRAINT uq_sched UNIQUE (medication_id, dose_time),
    CONSTRAINT fk_sched_med FOREIGN KEY (medication_id) REFERENCES medications(id) ON DELETE CASCADE
);

-- PHYSICAL STOCK only. Never derived from adherence data and vice versa.
CREATE TABLE medication_inventory (
    id                 BIGINT AUTO_INCREMENT PRIMARY KEY,
    medication_id      BIGINT NOT NULL,
    total_quantity     DECIMAL(8,2) NOT NULL,         -- what the parent started with / last refill
    remaining_quantity DECIMAL(8,2) NOT NULL,
    low_stock_threshold DECIMAL(8,2) NOT NULL DEFAULT 0,   -- 'low' when remaining <= this (added Day 3)
    updated_at         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT uq_inv_med UNIQUE (medication_id),
    CONSTRAINT fk_inv_med FOREIGN KEY (medication_id) REFERENCES medications(id) ON DELETE CASCADE,
    CONSTRAINT chk_inv_nonneg CHECK (remaining_quantity >= 0 AND remaining_quantity <= total_quantity)
);

-- DOSE HISTORY only. A row exists only when the parent confirms. No row = "pending" (never "missed").
-- UNIQUE(schedule_id, scheduled_date) blocks duplicate submissions; undo flips status to UNDONE.
CREATE TABLE medication_logs (
    id             BIGINT AUTO_INCREMENT PRIMARY KEY,
    medication_id  BIGINT NOT NULL,
    schedule_id    BIGINT NOT NULL,
    scheduled_date DATE NOT NULL,
    status         ENUM('TAKEN','UNDONE') NOT NULL DEFAULT 'TAKEN',
    quantity_deducted DECIMAL(8,2) NOT NULL DEFAULT 0,   -- stock taken off by this dose (added Day 4)
    taken_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    undone_at      TIMESTAMP NULL,
    CONSTRAINT uq_log_dose UNIQUE (schedule_id, scheduled_date),
    CONSTRAINT fk_log_med   FOREIGN KEY (medication_id) REFERENCES medications(id) ON DELETE CASCADE,
    CONSTRAINT fk_log_sched FOREIGN KEY (schedule_id)   REFERENCES medication_schedules(id) ON DELETE CASCADE,
    INDEX idx_log_med_date (medication_id, scheduled_date)
);

CREATE TABLE daily_checkins (
    id               BIGINT AUTO_INCREMENT PRIMARY KEY,
    parent_id        BIGINT NOT NULL,
    checkin_date     DATE NOT NULL,
    -- Day 5: GOOD / OKAY / NOT_GOOD are the values the app uses. The first four older values
    -- (VERY_GOOD, NORMAL, FEELING_LOW, FEELING_UNWELL) are kept only so old rows stay valid.
    feeling          ENUM('VERY_GOOD','GOOD','NORMAL','FEELING_LOW','FEELING_UNWELL','OKAY','NOT_GOOD') NOT NULL,
    energy_level     ENUM('HIGH','MODERATE','LOW') NULL,
    took_medicines   ENUM('YES','NO','MISSED_SOME') NULL,   -- legacy column, no longer used by the app
    symptoms         VARCHAR(500) NULL,
    comments         VARCHAR(500),                          -- the 'notes' field
    created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP NULL,
    CONSTRAINT uq_checkin_day UNIQUE (parent_id, checkin_date),
    CONSTRAINT fk_chk_parent FOREIGN KEY (parent_id) REFERENCES users(id) ON DELETE CASCADE
);

-- Day 4b: one row per physical tablet/capsule (the compartments of the blister strip)
CREATE TABLE medication_tablets (
    id            BIGINT AUTO_INCREMENT PRIMARY KEY,
    medication_id BIGINT NOT NULL,
    slot_number   INT NOT NULL,
    status        ENUM('AVAILABLE','TAKEN') NOT NULL DEFAULT 'AVAILABLE',
    taken_at      TIMESTAMP NULL,
    CONSTRAINT uq_tablet_slot UNIQUE (medication_id, slot_number),
    CONSTRAINT fk_tablet_med FOREIGN KEY (medication_id) REFERENCES medications(id) ON DELETE CASCADE,
    INDEX idx_tablet_med_status (medication_id, status)
);
